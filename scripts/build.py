#!/usr/bin/env python3
"""Generate a dependency-free, crawlable GitHub Pages homepage."""
import json
from pathlib import Path
from html import escape
from datetime import date

ROOT = Path(__file__).resolve().parents[1]
def read(name):
    return json.loads((ROOT / 'data' / f'{name}.json').read_text())
def e(value):
    return escape(str(value), quote=True)
def links(items, css='resource-links'):
    return f'<div class="{css}">' + ''.join(f'<a href="{e(url)}">{e(label)}</a>' for label, url in items) + '</div>'
def authors(items):
    return ', '.join((f'<strong>{e(a["name"])}</strong>' if a['name'] == 'Jun Zheng' else e(a['name'])) + ('<sup>*</sup>' if a.get('equal') else '') for a in items)
def paper(p):
    media = ''
    if p.get('media'):
        src = f'assets/previews/{p["media"]}'
        if p['media'] == 'Tstars-Tryon':
            media = f'<a class="paper-media" href="{e(p["links"][0][1])}" aria-label="Read {e(p["title"])}"><img src="{src}.webp" alt="Tstars-Tryon virtual try-on results" width="640" height="360" loading="lazy"></a>'
        else:
            media = f'<div class="paper-media"><video controls playsinline preload="none" poster="{src}.webp" aria-label="{e(p["title"])} demonstration"><source src="{src}.mp4" type="video/mp4"><a href="{src}.mp4">Watch demonstration</a></video></div>'
    role = f'<span class="role-label">{e(p["role"])}</span>' if p.get('role') else ''
    description = f'<p class="paper-description">{e(p["description"])}</p>' if p.get('description') else ''
    note = f'<p class="paper-note">{e(p["note"])}</p>' if p.get('note') else ''
    return f'''<article class="paper {'with-media' if media else 'text-paper'}" id="{e(p['id'])}">
      {media}<div class="paper-content"><div class="paper-meta"><span>{e(p['venue'])}</span>{role}</div>
      <h3><a href="{e(p['links'][0][1])}">{e(p['title'])}</a></h3>
      <p class="authors">{authors(p['authors'])}</p>{note}{description}{links(p['links'])}</div>
    </article>'''
def news_item(n):
    label=date.fromisoformat(n['date']+'-01').strftime('%b. %Y')
    return f'<li><time datetime="{n["date"]}">{label}</time><div>{e(n["text"])}{links(n["links"]) if n["links"] else ""}</div></li>'
def timeline(items):
    return ''.join(f'''<article class="timeline-item"><img src="assets/institutions/{e(x['logo'])}" width="48" height="48" loading="lazy" alt=""><div><div class="timeline-heading"><h3>{e(x['organization'])}</h3><span>{e(x['period'])}</span></div><p>{e(x['role'])}</p>{('<p class="muted">'+e(x['detail'])+'</p>') if x['detail'] else ''}{('<p class="previous">'+e(x['previous'])+'</p>') if x['previous'] else ''}</div></article>''' for x in items)

profile, papers, news = read('profile'), read('publications'), read('news')
assert len({p['id'] for p in papers}) == len(papers), 'Duplicate publication IDs'
selected = sorted((p for p in papers if p['selected']), key=lambda p:p['order'])
other = sorted((p for p in papers if not p['selected']), key=lambda p:-p['year'])
updated = date.fromisoformat(profile['updated']).strftime('%B %Y')
html = f'''<!doctype html>
<!-- Generated by scripts/build.py. Edit data/ or the generator, then rebuild. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Jun Zheng | Virtual Try-On Research</title>
  <meta name="description" content="Jun Zheng is an Algorithm Engineer at Alibaba, working on virtual try-on. Research, publications, and experience in visual generation.">
  <meta name="author" content="Jun Zheng">
  <meta property="og:type" content="website">
  <meta property="og:title" content="Jun Zheng | Virtual Try-On Research">
  <meta property="og:description" content="Algorithm Engineer at Alibaba. Research in virtual try-on and visual generation.">
  <meta property="og:url" content="https://zhengjun-ai.github.io/">
  <meta property="og:image" content="https://zhengjun-ai.github.io/assets/me.png">
  <meta name="twitter:card" content="summary">
  <link rel="canonical" href="https://zhengjun-ai.github.io/">
  <link rel="icon" type="image/png" href="assets/icon.png">
  <link rel="apple-touch-icon" href="assets/icon.png">
  <link rel="stylesheet" href="assets/style.css">
</head>
<body>
<a class="skip-link" href="#main">Skip to content</a>
<div class="page">
  <nav class="site-nav" aria-label="Main navigation"><a class="wordmark" href="#about">Jun Zheng<span aria-hidden="true">.</span></a><div><a href="#research">Research</a><a href="#experience">Experience</a><a href="mailto:zxbsmk@gmail.com">Contact</a></div></nav>
  <main id="main">
    <header class="intro" id="about">
      <div><p class="eyebrow">{e(profile['role'])} · {e(profile['organization'])}</p>
      <h1>{e(profile['name'])}</h1>
      <p class="lead">My research focuses on <strong>virtual try-on</strong>.</p>
      <p>I am an Algorithm Engineer in the {e(profile['department'])} department at Alibaba, where I work on virtual try-on. My broader research interests include image and video generation.</p>
      <p>I received my master’s degree in Control Science and Engineering from Sun Yat-sen University in June 2026, advised by Prof. <a href="https://scholar.google.com/citations?user=voxznZAAAAAJ">Xiaodan Liang</a>. I also received my bachelor’s degree from Sun Yat-sen University in 2023.</p>
      {links(profile['links'],'profile-links')}</div>
      <img class="portrait" src="assets/previews/portrait.webp" alt="Jun Zheng" width="224" height="224" fetchpriority="high">
    </header>
    <section class="news section" aria-labelledby="news-title"><div class="section-heading"><h2 id="news-title">News</h2><span>Recent updates</span></div>
    <ul class="news-list">{''.join(news_item(n) for n in news[:5])}</ul>
    <details class="older-news"><summary>Earlier updates</summary><ul class="news-list">{''.join(news_item(n) for n in news[5:])}</ul></details>
    </section>
    <section class="section" id="research" aria-labelledby="research-title"><div class="section-heading"><h2 id="research-title">Selected Research</h2><a href="{e(profile['links'][0][1])}">Google Scholar ↗</a></div>
    <p class="section-note">Virtual try-on and visual generation. <span>* Equal contribution.</span></p>
    {''.join(paper(p) for p in selected)}
    </section>
    <section class="section other-publications" aria-labelledby="other-title"><div class="section-heading"><h2 id="other-title">Other Publications</h2></div>
    {''.join(paper(p) for p in other)}
    </section>
    <section class="section" id="experience" aria-labelledby="experience-title"><div class="section-heading"><h2 id="experience-title">Experience</h2></div>{timeline(profile['experience'])}</section>
    <section class="section" id="education" aria-labelledby="education-title"><div class="section-heading"><h2 id="education-title">Education</h2></div>{timeline(profile['education'])}</section>
  </main>
  <footer><span>Jun Zheng</span><span>Last updated {updated}</span><a href="#about">Back to top ↑</a></footer>
</div>
</body>
</html>
'''
(ROOT/'index.html').write_text(html)
print(f'Built index.html: {len(selected)} selected + {len(other)} other publications.')
